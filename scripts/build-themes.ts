import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { checkTheme, contrastRatio, themeRules, type ThemeFile } from "../src/lib/contrast.ts"

const SOURCE_DIR = "src/themes"
const OUTPUT = "src/styles/themes.generated.css"

function loadThemes(): Array<ThemeFile> {
  const files = readdirSync(SOURCE_DIR).filter((file) => file.endsWith(".json"))

  return files
    .map((file) => JSON.parse(readFileSync(join(SOURCE_DIR, file), "utf8")) as ThemeFile)
    .sort((first, second) => first.order - second.order)
}

function declarations(theme: ThemeFile): string {
  const lines = Object.entries(theme.tokens).map(([token, value]) => `  ${token}: ${value};`)
  return [`  color-scheme: ${theme.scheme};`, ...lines].join("\n")
}

function build(theme: ThemeFile): string {
  return `[data-theme="${theme.name}"] {\n${declarations(theme)}\n}`
}

const themes = loadThemes()
const problems = themes.flatMap((theme) => checkTheme(theme))

if (problems.length > 0) {
  console.error("\nTheme contrast check failed:\n")
  for (const problem of problems) console.error(`  ✗ ${problem}`)
  console.error("")
  process.exit(1)
}

const light = themes.find((theme) => theme.name === "light") ?? themes[0]

const generated = [
  "/* Generated by scripts/build-themes.ts. Do not edit by hand. */",
  "",
  `:root {\n${declarations(light)}\n}`,
  "",
  themes.map(build).join("\n\n"),
  "",
].join("\n")

writeFileSync(OUTPUT, generated)

const summary = themes
  .map((theme) => {
    const body = themeRules(theme.tokens)[0]
    const ratio = contrastRatio(body.foreground, body.background)
    return `  ${theme.name.padEnd(9)} body ${ratio.toFixed(1)}:1`
  })
  .join("\n")

console.log(`themes: ${themes.length} written to ${OUTPUT}\n${summary}`)
